namespace GitHubReviewApp.Review;

/// <summary>
/// Decides which changed files the model cannot usefully read (lockfiles, binaries, minified bundles), how much is at stake in each of
/// the rest (its risk tier), and so in which order they are reviewed when the budget is tight. Generated and vendored code is demoted
/// to the end of the queue rather than dropped: it still compiles and runs, and its author controls both its name and its comments.
/// </summary>
public static class DiffFileClassifier
{
    // A generated-file header counts only among the first few lines of a new file.
    private const int GeneratedHeaderLines = 5;

    private static readonly HashSet<string> _lockfileNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb",
        "packages.lock.json", "paket.lock", "go.sum", "Cargo.lock", "poetry.lock", "Pipfile.lock",
        "Gemfile.lock", "composer.lock", "Podfile.lock", "pubspec.lock", "mix.lock", "gradle.lockfile",
        "flake.lock", "project.assets.json"
    };

    private static readonly string[] _minifiedSuffixes = [".min.js", ".min.css", ".map"];

    private static readonly HashSet<string> _binaryExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".png", ".jpg", ".jpeg", ".gif", ".ico", ".bmp", ".webp", ".avif", ".pdf", ".zip", ".gz", ".tar",
        ".7z", ".rar", ".jar", ".war", ".dll", ".exe", ".pdb", ".so", ".dylib", ".nupkg", ".woff", ".woff2",
        ".ttf", ".otf", ".eot", ".mp3", ".mp4", ".mov", ".wav", ".bin"
    };

    // Binaries that can run or carry other files: a new one is worth a human's attention even though nobody reads its bytes.
    private static readonly HashSet<string> _executableOrArchiveExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".dll", ".exe", ".jar", ".war", ".so", ".dylib", ".nupkg", ".zip", ".gz", ".tar", ".7z", ".rar", ".bin"
    };

    private static readonly string[] _generatedSuffixes =
    [
        ".designer.cs", ".g.cs", ".g.i.cs", ".generated.cs", ".generated.ts", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".snap", "modelsnapshot.cs"
    ];

    private static readonly HashSet<string> _vendoredDirectories = new(StringComparer.OrdinalIgnoreCase)
    {
        "node_modules", "vendor", "third_party", "bower_components", "bin", "obj", "dist",
        ".vs", ".idea", "__pycache__", "coverage"
    };

    // The header of a file generated from the very first line: "-0,0 +1,N" is a file that did not exist before.
    private static readonly Regex _newFileHunkHeader = new(@"^@@ -0,0 \+1(,\d+)? @@", RegexOptions.Compiled | RegexOptions.CultureInvariant);

    // The forms real generators write. A loose phrase such as "do not edit" is not one: any author can put it in any comment.
    private static readonly Regex[] _canonicalGeneratedMarkers =
    [
        new(@"^\s*(?://|#|/\*+|\*|--|;)\s*<auto-generated", RegexOptions.Compiled | RegexOptions.CultureInvariant | RegexOptions.IgnoreCase),
        new(@"^\s*(?://|#|/\*+|\*|--|;)\s*@generated\b", RegexOptions.Compiled | RegexOptions.CultureInvariant),
        new(@"^\s*//\s*Code generated\b.*\bDO NOT EDIT\.?\s*$", RegexOptions.Compiled | RegexOptions.CultureInvariant)
    ];

    private static readonly HashSet<string> _documentationExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".md", ".mdx", ".markdown", ".txt", ".rst", ".adoc"
    };

    // Licence and notice files, whatever their extension. They are documentation, though "license" is also a personal-data keyword.
    private static readonly HashSet<string> _licenceNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "LICENSE", "LICENCE", "COPYING", "NOTICE"
    };

    private static readonly string[] _licenceNamePrefixes = ["LICENSE-", "LICENCE-"];

    private static readonly HashSet<string> _sourceExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".cs", ".vb", ".fs", ".csx", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".vue", ".svelte", ".py",
        ".java", ".kt", ".kts", ".scala", ".go", ".rs", ".rb", ".php", ".swift", ".c", ".cc", ".cpp", ".h",
        ".hpp", ".m", ".sql", ".sh", ".bash", ".ps1", ".psm1", ".psd1", ".bat", ".cmd", ".razor", ".cshtml",
        ".bicep", ".tf", ".proto", ".graphql", ".gql"
    };

    private static readonly HashSet<string> _configurationExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".json", ".jsonc", ".yml", ".yaml", ".xml", ".csproj", ".vbproj", ".fsproj", ".props", ".targets",
        ".sln", ".slnx", ".toml", ".ini", ".config", ".editorconfig", ".env", ".properties", ".gradle"
    };

    private static readonly HashSet<string> _testDirectoryNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "test", "tests", "__tests__", "spec", "specs", "e2e"
    };

    private static readonly string[] _testDirectorySuffixes =
    [
        ".tests", ".test", ".unittests", ".integrationtests", ".specs"
    ];

    private static readonly HashSet<string> _documentationDirectoryNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "docs", "doc"
    };

    private static readonly HashSet<string> _infrastructureExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".bicep", ".bicepparam", ".tf", ".tfvars"
    };

    private static readonly HashSet<string> _pipelineDirectoryNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "pipelines", ".azuredevops", "infra", "deploy", "deployment", "helm", "charts", "k8s", "kubernetes"
    };

    // Source code that a pipeline folder holds as part of the pipeline: scripts and infrastructure as code. Any other source code in a folder
    // of that name is the application's ("src/components/charts/LineChart.vue").
    private static readonly HashSet<string> _scriptAndInfrastructureExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".sh", ".bash", ".ps1", ".psm1", ".psd1", ".bat", ".cmd", ".bicep", ".tf"
    };

    /// <summary>Why a file cannot be reviewed as text, judged from its path alone, or null when it can.</summary>
    public static FileSkipReason? GetSkipReason(string path)
    {
        var segments = SplitPath(path);

        if (segments.Length == 0)
        {
            return null;
        }

        var fileName = segments[^1];

        if (IsLockfileName(fileName))
        {
            return FileSkipReason.DependencyLockfile;
        }

        return IsBinaryOrMinifiedName(fileName) ? FileSkipReason.BinaryOrMinified : null;
    }

    /// <summary>
    /// How much is at stake in a changed file (design 5.3). The first rule that matches wins: a lockfile, binary or minified file is not
    /// readable; then generated or vendored code; tests; documentation; the high-risk areas, by the words of the path; pipelines, container
    /// files and infrastructure as code; configuration; and everything else is source. Tests, documentation and generated code come before
    /// the keywords, so a test of the login code is a test and not an auth file.
    /// </summary>
    public static RiskTier GetRiskTier(PullRequestFile file)
    {
        var segments = SplitPath(file.Path);
        var fileName = segments.Length == 0 ? string.Empty : segments[^1];

        if (IsLockfileName(fileName) || IsBinaryOrMinifiedName(fileName))
        {
            return RiskTier.NotReadable;
        }

        if (IsGeneratedOrVendoredPath(segments, fileName) || IsNewFileWithGeneratedHeader(file.Status, file.Patch))
        {
            return RiskTier.GeneratedOrVendored;
        }

        if (IsTestPath(segments, fileName))
        {
            return RiskTier.Tests;
        }

        if (IsDocumentationPath(segments, fileName))
        {
            return RiskTier.Docs;
        }

        if (RiskKeywords.MatchHighRiskTier(file.Path) is { } highRiskTier)
        {
            return highRiskTier;
        }

        if (IsPipelinePath(segments, fileName))
        {
            return RiskTier.Pipelines;
        }

        if (IsConfigurationName(fileName))
        {
            return RiskTier.Config;
        }

        return RiskTier.Source;
    }

    /// <summary>True for a dependency lockfile, such as package-lock.json, yarn.lock or packages.lock.json.</summary>
    public static bool IsLockfile(string path)
    {
        var segments = SplitPath(path);

        return segments.Length > 0 && IsLockfileName(segments[^1]);
    }

    /// <summary>
    /// True for a documentation file (.md, .mdx, .markdown, .txt, .rst or .adoc), for a licence file (LICENSE, LICENCE, COPYING or NOTICE,
    /// whatever its extension, and LICENSE-* or LICENCE-*), and for anything inside a docs or doc folder.
    /// </summary>
    public static bool IsDocumentation(string path)
    {
        var segments = SplitPath(path);

        return segments.Length > 0 && IsDocumentationPath(segments, segments[^1]);
    }

    /// <summary>True for a binary that can run or carry other files, such as a library, an executable or an archive.</summary>
    public static bool IsExecutableOrArchive(string path)
    {
        return _executableOrArchiveExtensions.Contains(Path.GetExtension(path));
    }

    public static FilePriority GetPriority(string path, string status = "modified", string? patch = null)
    {
        var segments = SplitPath(path);

        if (segments.Length == 0)
        {
            return FilePriority.Other;
        }

        var fileName = segments[^1];
        var extension = Path.GetExtension(fileName);

        if (IsGeneratedOrVendoredPath(segments, fileName) || IsNewFileWithGeneratedHeader(status, patch))
        {
            return FilePriority.GeneratedOrVendored;
        }

        if (_documentationExtensions.Contains(extension))
        {
            return FilePriority.Other;
        }

        if (IsPipelineOrContainerFile(segments, fileName))
        {
            return FilePriority.Source;
        }

        if (IsTestPath(segments, fileName))
        {
            return FilePriority.Tests;
        }

        if (_sourceExtensions.Contains(extension))
        {
            return FilePriority.Source;
        }

        if (_configurationExtensions.Contains(extension))
        {
            return FilePriority.Configuration;
        }

        return FilePriority.Other;
    }

    private static string[] SplitPath(string path)
    {
        return path.Replace('\\', '/').Split('/', StringSplitOptions.RemoveEmptyEntries);
    }

    private static bool IsLockfileName(string fileName)
    {
        return _lockfileNames.Contains(fileName);
    }

    private static bool IsBinaryOrMinifiedName(string fileName)
    {
        var isMinified = _minifiedSuffixes.Any(suffix => fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase));

        return isMinified || _binaryExtensions.Contains(Path.GetExtension(fileName));
    }

    private static bool IsDocumentationPath(string[] segments, string fileName)
    {
        return _documentationExtensions.Contains(Path.GetExtension(fileName))
            || IsLicenceName(fileName)
            || segments.SkipLast(1).Any(_documentationDirectoryNames.Contains);
    }

    private static bool IsLicenceName(string fileName)
    {
        var name = Path.GetFileNameWithoutExtension(fileName);

        return _licenceNames.Contains(name) || _licenceNamePrefixes.Any(prefix => name.StartsWith(prefix, StringComparison.OrdinalIgnoreCase));
    }

    // A build or release pipeline, a container file, infrastructure as code, or a file inside a folder that holds them, unless that file is
    // the application's own code: a source file there is a pipeline file only when it is a script or infrastructure as code.
    private static bool IsPipelinePath(string[] segments, string fileName)
    {
        var extension = Path.GetExtension(fileName);
        var isApplicationCode = _sourceExtensions.Contains(extension) && !_scriptAndInfrastructureExtensions.Contains(extension);

        return IsPipelineOrContainerFile(segments, fileName)
            || _infrastructureExtensions.Contains(extension)
            || (!isApplicationCode && segments.SkipLast(1).Any(_pipelineDirectoryNames.Contains));
    }

    private static bool IsConfigurationName(string fileName)
    {
        return _configurationExtensions.Contains(Path.GetExtension(fileName))
            || fileName.StartsWith(".env", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsGeneratedOrVendoredPath(string[] segments, string fileName)
    {
        if (_generatedSuffixes.Any(suffix => fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return true;
        }

        for (var index = 0; index < segments.Length - 1; index++)
        {
            if (_vendoredDirectories.Contains(segments[index]))
            {
                return true;
            }

            var isLibmanFolder = index > 0
                && segments[index].Equals("lib", StringComparison.OrdinalIgnoreCase)
                && segments[index - 1].Equals("wwwroot", StringComparison.OrdinalIgnoreCase);

            if (isLibmanFolder)
            {
                return true;
            }
        }

        return false;
    }

    private static bool IsNewFileWithGeneratedHeader(string status, string? patch)
    {
        // For a changed file the first lines of the patch are whatever the author chose to touch, not the top of the file. Only a
        // new file, whose first hunk starts at line 1, shows its real header, and even then only a few canonical forms count.
        if (!status.Equals("added", StringComparison.OrdinalIgnoreCase) || string.IsNullOrEmpty(patch))
        {
            return false;
        }

        var lines = patch.Split('\n');

        if (!_newFileHunkHeader.IsMatch(lines[0]))
        {
            return false;
        }

        return lines.Skip(1)
            .TakeWhile(line => line.StartsWith('+'))
            .Take(GeneratedHeaderLines)
            .Any(line => _canonicalGeneratedMarkers.Any(marker => marker.IsMatch(line[1..].TrimEnd('\r'))));
    }

    private static bool IsPipelineOrContainerFile(string[] segments, string fileName)
    {
        var isWorkflow = segments.Length >= 3
            && segments[^3].Equals(".github", StringComparison.OrdinalIgnoreCase)
            && segments[^2].Equals("workflows", StringComparison.OrdinalIgnoreCase);

        return isWorkflow
            || fileName.Equals("Dockerfile", StringComparison.OrdinalIgnoreCase)
            || fileName.StartsWith("Dockerfile.", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".dockerfile", StringComparison.OrdinalIgnoreCase)
            || fileName.StartsWith("azure-pipelines", StringComparison.OrdinalIgnoreCase)
            || fileName.Equals(".gitlab-ci.yml", StringComparison.OrdinalIgnoreCase)
            || fileName.Equals("Jenkinsfile", StringComparison.Ordinal);
    }

    private static bool IsTestPath(string[] segments, string fileName)
    {
        for (var index = 0; index < segments.Length - 1; index++)
        {
            var directory = segments[index];

            if (_testDirectoryNames.Contains(directory))
            {
                return true;
            }

            foreach (var suffix in _testDirectorySuffixes)
            {
                if (directory.EndsWith(suffix, StringComparison.OrdinalIgnoreCase))
                {
                    return true;
                }
            }
        }

        // Case-sensitive on purpose: "OrderTests.cs" is a test, "Latest.cs" is not.
        return fileName.EndsWith("Tests.cs", StringComparison.Ordinal)
            || fileName.EndsWith("Test.cs", StringComparison.Ordinal)
            || fileName.Contains(".test.", StringComparison.OrdinalIgnoreCase)
            || fileName.Contains(".spec.", StringComparison.OrdinalIgnoreCase)
            || (fileName.StartsWith("test_", StringComparison.OrdinalIgnoreCase) && fileName.EndsWith(".py", StringComparison.OrdinalIgnoreCase))
            || fileName.EndsWith("_test.py", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith("_test.go", StringComparison.OrdinalIgnoreCase);
    }
}
